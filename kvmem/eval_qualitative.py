"""
kvmem/eval_qualitative.py — qualitative decode inspection for any HMNModel
checkpoint: runs a real trajectory through the model and prints/saves
ground-truth vs. generated bytes per query, not just match% (which
eval_weave.py already covers). Useful for seeing HOW a checkpoint fails —
e.g. distinguishing "degrades into plausible-but-wrong bytes" from
"collapses into pure non-printable noise" — a distinction match% alone
can't show.

Usage:
    python3 -m kvmem.eval_qualitative <ckpt> --device mps
    python3 -m kvmem.eval_qualitative <ckpt> --patterns batch,stream --seq-idx 1 --out report.txt
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import torch

from kvmem.hmn import (_cyclic_state_ids, build_model, chunk_positions_traj,
                       chunk_mask_fb_traj, make_test_sequences, traj_batch,
                       traj_stream, traj_interleave_delayed)

_PATTERNS = dict(batch=traj_batch, stream=traj_stream, interleave_delayed=traj_interleave_delayed)


def _load(ckpt_path: str, device: torch.device):
    ckpt = torch.load(ckpt_path, map_location=device)
    hp = ckpt['hp']
    hp_model = dict(V=hp['V'], d=hp['d'], n_layers=hp['n_layers'], n_heads=hp['n_heads'],
                    block_type=hp.get('block_type', 'single_attn'),
                    rope=hp.get('rope', True), yarn=hp.get('yarn', True),
                    null_kv=hp.get('null_kv', True), rmsnorm=hp.get('rmsnorm', False), chunk_attn=0)
    model = build_model(hp_model, device)
    model.load_state_dict(ckpt['model'], strict=False)
    model.eval()
    return model, hp


def _fmt(byte_arr) -> str:
    """Printable-safe repr: printable ASCII as-is, else \\xNN."""
    return ''.join(chr(b) if 0x20 <= b < 0x7f else f'\\x{b:02x}' for b in byte_arr)


@torch.no_grad()
def decode_and_show(model, hp: dict, pattern_name: str, n_chunks: int, chunk_len: int,
                    window_chunks: int, device: torch.device, seq_idx: int, out) -> None:
    """`out`: any object with a .write(str) method (e.g. an open file or a
    small tee-to-stdout-and-file wrapper) — the report is written there,
    not printed directly, so callers control where it ends up."""
    state_len = hp.get('state_len', 8)
    state_vocab_size = hp.get('state_vocab_size', 2)
    warmup_len = hp['warmup_len']

    ops = _PATTERNS[pattern_name](n_chunks, window_chunks)
    built = chunk_positions_traj(chunk_len, state_len, warmup_len, ops, n_refine=0,
                                 state_vocab_size=state_vocab_size)
    pos_content, pos_mask, tags = built['pos_content'], built['pos_mask'], built['tags']
    mask_np = chunk_mask_fb_traj(pos_mask)

    val_seqs = make_test_sequences(n_chunks * chunk_len)
    name, seq_bytes = list(val_seqs.items())[seq_idx % len(val_seqs)]
    chunks_list = [np.array(seq_bytes[k * chunk_len:(k + 1) * chunk_len]) for k in range(n_chunks)]

    wl = warmup_len
    sids = np.array(_cyclic_state_ids(state_len, state_vocab_size), dtype=np.int64)
    L = pos_content['L']
    full_mask = torch.tensor(mask_np, dtype=torch.float32, device=device)

    tok = np.zeros(L, dtype=np.int64)
    for k, b in enumerate(pos_content['enc_blocks']):
        tok[b['s0']:b['s1']] = chunks_list[k]
        tok[b['sl0']:b['sl1']] = sids
    tag_pos = np.array([p for p, _ in tags], dtype=np.int64)
    tag_ids = np.array([i for _, i in tags], dtype=np.int64)
    tok[tag_pos] = tag_ids

    def fwd_at(pos):
        t = torch.tensor(tok[:pos], dtype=torch.long, device=device)
        m = full_mask[:pos, :pos]
        return model(t, m)[-1]

    out.write(f'\n=== pattern={pattern_name}  seq={name}  n_chunks={n_chunks} ===\n')
    decoded_by_span = {}
    for i, rb in enumerate(pos_content['rec_blocks']):
        if rb['type'] == 'noop':
            tok[rb['sl0']:rb['sl1']] = sids
            continue
        span_s, span_e = rb['span']
        gt_span = np.concatenate(chunks_list[span_s:span_e])
        if span_s == 0 and rb['span'] not in decoded_by_span:
            warmup_src = gt_span[:wl]
        else:
            warmup_src = decoded_by_span.get(rb['span'], gt_span)[:wl]

        tok[rb['sl0']:rb['sl1']] = sids
        if wl > 0:
            tok[rb['w0']:rb['w1']] = warmup_src
        for j in range(rb['out_len']):
            pos = rb['c0'] + j
            tok[pos] = int(fwd_at(pos).argmax())

        rb_target = gt_span[wl:wl + rb['out_len']]
        rb_gen = tok[rb['c0']:rb['c1']]
        decoded_by_span[rb['span']] = np.concatenate([warmup_src, rb_gen])

        match = 100.0 * np.sum(rb_gen == rb_target) / max(len(rb_target), 1)
        diff_mask = ''.join('.' if a == b else '^' for a, b in zip(rb_gen, rb_target))
        out.write(f'\n--- op{i} span={rb["span"]} match={match:.1f}% ---\n')
        out.write(f'  warmup (GT) : {_fmt(warmup_src)}\n')
        out.write(f'  target (GT) : {_fmt(rb_target)}\n')
        out.write(f'  generated   : {_fmt(rb_gen)}\n')
        out.write(f'  diff        : {diff_mask}\n')


class _Tee:
    """Writes to stdout and an open file simultaneously."""
    def __init__(self, f):
        self.f = f
    def write(self, s: str) -> None:
        print(s, end='')
        self.f.write(s)


def main():
    p = argparse.ArgumentParser(description='Qualitative decode inspection for an HMNModel checkpoint')
    p.add_argument('ckpt')
    p.add_argument('--device', default='cpu')
    p.add_argument('--patterns', default='batch,stream,interleave_delayed')
    p.add_argument('--n-chunks', type=int, default=4)
    p.add_argument('--chunk-len', type=int, default=16)
    p.add_argument('--window-chunks', type=int, default=2)
    p.add_argument('--seq-idx', type=int, default=0)
    p.add_argument('--out', default=None,
                   help='report file path; defaults to <ckpt run dir>/qualitative_decode.txt '
                        '(e.g. logs/<name>/checkpoints/stage0_best.pt -> logs/<name>/qualitative_decode.txt)')
    args = p.parse_args()

    ckpt_path = Path(args.ckpt)
    out_path = Path(args.out) if args.out else ckpt_path.parent.parent / 'qualitative_decode.txt'
    out_path.parent.mkdir(parents=True, exist_ok=True)

    device = torch.device(args.device)
    model, hp = _load(args.ckpt, device)

    with open(out_path, 'w') as f:
        tee = _Tee(f)
        tee.write(f'checkpoint: {args.ckpt}\n')
        for pat in args.patterns.split(','):
            decode_and_show(model, hp, pat, args.n_chunks, args.chunk_len, args.window_chunks,
                            device, args.seq_idx, tee)
    print(f'\n[saved to {out_path}]')


if __name__ == '__main__':
    main()
